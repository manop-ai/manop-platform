-- phase24_paystack_payments.sql  (UNAPPLIED; requires phase22; idempotent)
-- Server-side record of every Paystack payment attempt for MANOP's OWN charges (subscriptions now; fee invoices later).
-- Never used for property purchase funds. The browser has no access; the status here comes from Paystack's server-verified result.
create table if not exists public.paystack_payments (
  id               uuid primary key default gen_random_uuid(),
  reference        text not null unique,                       -- generated by MANOP, sent to Paystack
  purpose          text not null check (purpose in ('agency_subscription')),
  subscription_id  uuid references public.agency_subscriptions(id),
  agency_id        uuid not null references public.data_partners(id),
  amount_minor     bigint not null check (amount_minor > 0),    -- kobo; computed on the server from the accepted proposal
  currency         text not null check (currency in ('NGN')),
  status           text not null default 'initialized' check (status in ('initialized','pending','succeeded','failed','abandoned','mismatch')),
  environment      text not null default 'test' check (environment in ('test','live')),
  paystack_transaction_id text,
  authorization_url text,
  verified_at      timestamptz,
  failure_reason   text,
  initiated_by     uuid not null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create unique index if not exists paystack_one_success_per_subscription on public.paystack_payments (subscription_id) where status = 'succeeded';
create index if not exists paystack_payments_agency_idx on public.paystack_payments (agency_id, created_at desc);

-- webhook idempotency: each Paystack event is processed once
create table if not exists public.paystack_events (
  id          uuid primary key default gen_random_uuid(),
  event_key   text not null unique,                 -- event + reference (+ Paystack transaction id)
  event_type  text not null,
  reference   text,
  signature_valid boolean not null,
  outcome     text not null,
  received_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['paystack_payments','paystack_events'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_admin_select', t);
    execute format('create policy %I on public.%I for select to authenticated using (is_manop_admin())', t || '_admin_select', t);
    execute format('drop policy if exists %I on public.%I', t || '_service_all', t);
    execute format('create policy %I on public.%I for all to service_role using (true) with check (true)', t || '_service_all', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
    execute format('grant select, insert, update on public.%I to service_role', t);
  end loop;
end $$;
-- ROLLBACK: drop table public.paystack_events; drop table public.paystack_payments;
